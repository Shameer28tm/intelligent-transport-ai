def seed_database(db: Session, force: bool = False):
    """
    Seed initial simulated demonstration incidents into the database.
    Explicitly tags every record as SIMULATED DEMO DATA.
    """
    existing_count = db.query(Incident).count()
    if existing_count > 0 and not force:
        return existing_count

    now = datetime.now(timezone.utc)
    for data in SEED_INCIDENTS:
        created_time = now - timedelta(hours=data["hours_ago"])
        resolved_time = created_time + timedelta(hours=2) if data["status"] == IncidentStatus.RESOLVED else None

        incident = Incident(
            id=str(uuid.uuid4()),
            title=data["title"],
            description=data["description"],
            category=data["category"],
            severity=data["severity"],
            status=data["status"],
            latitude=data["latitude"],
            longitude=data["longitude"],
            location_name=data["location_name"],
            corridor=data["corridor"],
            speed_limit_kmh=data["speed_limit_kmh"],
            current_speed_kmh=data["current_speed_kmh"],
            congestion_level_pct=data["congestion_level_pct"],
            affected_lanes=data["affected_lanes"],
            is_simulated=True,
            data_source="SIMULATED DEMO DATA",
            tags=data["tags"],
            created_at=created_time,
            updated_at=created_time,
            resolved_at=resolved_time,
        )
        db.add(incident)

    db.commit()
    return len(SEED_INCIDENTS)


def replace_demo_incidents(db: Session) -> int:
    """
    Replace ONLY simulated demo incidents (is_simulated=True) with the current seed set.
    Real, non-simulated incident rows are never touched.
    """
    db.query(Incident).filter(Incident.is_simulated.is_(True)).delete(synchronize_session=False)
    db.commit()
    seed_database(db, force=True)
    return len(SEED_INCIDENTS)


if __name__ == "__main__":
    import argparse

    from app.database import Base, SessionLocal, engine

    parser = argparse.ArgumentParser(description="Seed or refresh simulated demo incidents.")
    parser.add_argument("--replace-demo", action="store_true",
                        help="Delete simulated demo incidents only, then insert the Tamil Nadu demo set.")
    args = parser.parse_args()
    Base.metadata.create_all(bind=engine)
    session = SessionLocal()
    try:
        if args.replace_demo:
            n = replace_demo_incidents(session)
            print(f"Replaced simulated demo incidents with {n} Tamil Nadu demo records (real records untouched).")
        else:
            print(f"Database has {seed_database(session)} incidents (seeded only if it was empty).")
    finally:
        session.close()
